param(
    [ValidateSet('paper','slides','all')][string]$Target = 'all',
    [switch]$Render,
    [ValidatePattern('^(-[a-zA-Z0-9]+)*$')][string]$PdfSuffix = ''
)
$ErrorActionPreference = 'Stop'
$docRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$buildRoot = Join-Path $docRoot 'build'
New-Item -ItemType Directory -Force -Path $buildRoot | Out-Null
$targets = if ($Target -eq 'all') { @('paper','slides') } else { @($Target) }
Push-Location $docRoot
try {
    foreach ($name in $targets) {
        $texPath = Join-Path $docRoot ($name + '.tex')
        if (-not (Test-Path -LiteralPath $texPath)) { throw "Missing source: $texPath" }
        $outputLog = Join-Path $buildRoot ($name + '-build.txt')
        & pdflatex -interaction=nonstopmode -halt-on-error -file-line-error -output-directory=build ($name + '.tex') *> $outputLog
        if ($LASTEXITCODE -ne 0) { throw "LaTeX failed. See $outputLog" }
        if ($name -eq 'paper') {
            Push-Location $buildRoot
            try {
                $previousBibInputs = $env:BIBINPUTS
                $env:BIBINPUTS = $docRoot + [IO.Path]::PathSeparator + $previousBibInputs
                & bibtex paper *>> $outputLog
                if ($LASTEXITCODE -ne 0) { throw "BibTeX failed. See $outputLog" }
            } finally { $env:BIBINPUTS = $previousBibInputs; Pop-Location }
        }
        for ($pass = 0; $pass -lt 2; $pass++) {
            & pdflatex -interaction=nonstopmode -halt-on-error -file-line-error -output-directory=build ($name + '.tex') *>> $outputLog
            if ($LASTEXITCODE -ne 0) { throw "LaTeX failed. See $outputLog" }
        }
        $logText = Get-Content -LiteralPath (Join-Path $buildRoot ($name + '.log')) -Raw
        if ($logText -match 'There were undefined references|There were undefined citations|LaTeX Warning: (Reference|Citation).*undefined') {
            throw "Unresolved references in $name. See $outputLog"
        }
        # A suffix lets a new edition be built while an earlier PDF is open.
        $pdfPath = Join-Path $docRoot ($name + $PdfSuffix + '.pdf')
        Copy-Item -LiteralPath (Join-Path $buildRoot ($name + '.pdf')) -Destination $pdfPath -Force
        if ($Render) {
            $renderRoot = Join-Path $buildRoot ($name + '-pages')
            New-Item -ItemType Directory -Force -Path $renderRoot | Out-Null
            # Remove only previews generated by earlier builds, so a shorter PDF
            # cannot leave stale final pages in the review sheets.
            Get-ChildItem -LiteralPath $renderRoot -Filter 'page-*.png' -File | ForEach-Object {
                Remove-Item -LiteralPath $_.FullName
            }
            & pdftoppm -r 100 -png $pdfPath (Join-Path $renderRoot 'page') 2>> $outputLog
            if ($LASTEXITCODE -ne 0) { throw "PDF rendering failed. See $outputLog" }
        }
        Write-Output ('Built ' + [IO.Path]::GetFileName($pdfPath))
        Select-String -LiteralPath (Join-Path $buildRoot ($name + '.log')) -Pattern 'Overfull|Underfull' | ForEach-Object { $_.Line }
    }
} finally { Pop-Location }
